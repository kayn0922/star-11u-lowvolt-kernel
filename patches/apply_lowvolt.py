#!/usr/bin/env python3
# SPDX-License-Identifier: GPL-2.0-only
"""
Apply the "star / Mi 11 Ultra low-voltage kernel" changes to a checkout of
ikun-1145141/android_kernel_xiaomi_sm8350_star (branch venus-5.10bpf).

Exact-string / single-match-regex replacements are used instead of unified
diffs, so the patcher fails loudly (rather than silently) if upstream changes.

Environment:
  LOWVOLT_SHUTDOWN_MV   emergency power-off voltage in mV   (default 2980)
  LOWVOLT_VSOC_TABLE    "mV:percent,..." table              (default: config/volt_soc_table.default.txt)
  LOWVOLT_LOCALVERSION  suffix added to LOCALVERSION        (default -lowvolt-<mV>mv)
"""
from __future__ import annotations

import os
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
KERNEL = Path(sys.argv[1] if len(sys.argv) > 1 else os.environ.get("KERNEL_DIR", ".")).resolve()

SHUTDOWN_MV = int(os.environ.get("LOWVOLT_SHUTDOWN_MV", "2980"))
if not 2500 <= SHUTDOWN_MV <= 3400:
    sys.exit(f"LOWVOLT_SHUTDOWN_MV out of range: {SHUTDOWN_MV}")

TABLE = os.environ.get("LOWVOLT_VSOC_TABLE", "").strip()
if not TABLE:
    TABLE = (REPO / "config" / "volt_soc_table.default.txt").read_text(encoding="utf-8").strip()
if len(TABLE) > 900:
    sys.exit("LOWVOLT_VSOC_TABLE is too long (max 900 chars)")
if not re.fullmatch(r"[0-9]+[:=][0-9]+(?:[,;\s]+[0-9]+[:=][0-9]+)+", TABLE):
    sys.exit("LOWVOLT_VSOC_TABLE has an invalid format; expected 'mV:percent,mV:percent,...'")

LOCALVERSION = os.environ.get("LOWVOLT_LOCALVERSION", f"-lowvolt-{SHUTDOWN_MV}mv").strip()

SUPPLY = Path("drivers/power/supply")
changes: list[str] = []


def read(rel: Path) -> str:
    p = KERNEL / rel
    if not p.is_file():
        sys.exit(f"missing file: {p}")
    with open(p, "r", encoding="utf-8", newline="") as f:
        return f.read()


def write(rel: Path, text: str) -> None:
    p = KERNEL / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def sub(rel: Path, old: str, new: str, label: str) -> str:
    text = read(rel)
    count = text.count(old)
    if count != 1:
        sys.exit(f"[{label}] {rel}: expected exactly 1 match, found {count}\n"
                 f"--- searched for ---\n{old!r}")
    text = text.replace(old, new, 1)
    write(rel, text)
    changes.append(f"{rel}: {label}")
    return text


def resub(rel: Path, pattern: str, replacement, label: str) -> str:
    text = read(rel)
    text, count = re.subn(pattern, replacement, text, count=1, flags=re.M)
    if count != 1:
        sys.exit(f"[{label}] {rel}: expected exactly 1 regex match, found {count}\n"
                 f"--- pattern ---\n{pattern}")
    write(rel, text)
    changes.append(f"{rel}: {label}")
    return text


# ---------------------------------------------------------------------------
# 1. New driver sources.  The header is generated so workflow inputs become
#    the compiled-in defaults.
# ---------------------------------------------------------------------------
shutil.copyfile(REPO / "overlay" / SUPPLY / "star_volt_soc.c",
                KERNEL / SUPPLY / "star_volt_soc.c")
changes.append(f"{SUPPLY / 'star_volt_soc.c'}: added driver")

header = f'''/* SPDX-License-Identifier: GPL-2.0-only */
/* Generated by patches/apply_lowvolt.py - edit config/volt_soc_table.default.txt
 * or the workflow inputs instead of editing this file by hand. */
#ifndef _STAR_VOLT_SOC_H
#define _STAR_VOLT_SOC_H

/* Emergency power-off voltage in mV.  Stock is 3400, this build uses 2980. */
#define STAR_VOLT_SOC_SHUTDOWN_MV {SHUTDOWN_MV}

/* Voltage (mV) -> displayed battery percentage, strictly ascending voltage. */
#define STAR_VOLT_SOC_DEFAULT_TABLE "{TABLE}"

#ifdef CONFIG_STAR_VOLT_SOC
int star_volt_soc_apply(int raw_soc, int volt_uv, int status);
int star_volt_soc_shutdown_mv(void);
int star_volt_soc_hardcutoff_mv(void);
bool star_volt_soc_should_shutdown(int raw_mv);
int star_volt_soc_report_volt_uv(int raw_uv, int status);
int star_volt_soc_scale_cc(int raw_uah, int full_uah);
#else
static inline int star_volt_soc_apply(int raw_soc, int volt_uv, int status)
{{
    return raw_soc;
}}
static inline int star_volt_soc_shutdown_mv(void)
{{
    return STAR_VOLT_SOC_SHUTDOWN_MV;
}}
static inline int star_volt_soc_hardcutoff_mv(void)
{{
    return 2900;
}}
static inline bool star_volt_soc_should_shutdown(int raw_mv)
{{
    return false;
}}
static inline int star_volt_soc_report_volt_uv(int raw_uv, int status)
{{
    return raw_uv;
}}
static inline int star_volt_soc_scale_cc(int raw_uah, int full_uah)
{{
    return raw_uah;
}}
#endif
#endif /* _STAR_VOLT_SOC_H */
'''
write(SUPPLY / "star_volt_soc.h", header)
changes.append(f"{SUPPLY / 'star_volt_soc.h'}: generated (shutdown={SHUTDOWN_MV} mV)")

# ---------------------------------------------------------------------------
# 2. Kconfig + Makefile
# ---------------------------------------------------------------------------
kconfig_entry = (
    "config STAR_VOLT_SOC\n"
    "\tbool \"star: rebuildable voltage -> battery SOC table\"\n"
    "\tdepends on QTI_PMIC_GLINK\n"
    "\tdefault y\n"
    "\thelp\n"
    "\t  Runtime-rewritable voltage-to-percentage mapping for the battery\n"
    "\t  power supply, plus one tunable emergency shutdown voltage.  Used\n"
    "\t  by the low-voltage Xiaomi 11 Ultra (star) build.\n\n"
)
sub(SUPPLY / "Kconfig", "config DUAL_FUEL_GAUGE\n",
    kconfig_entry + "config DUAL_FUEL_GAUGE\n", "add CONFIG_STAR_VOLT_SOC")

sub(SUPPLY / "Makefile",
    "obj-$(CONFIG_QTI_BATTERY_CHARGER_VENUS)\t+= qti_battery_charger_venus.o\n",
    "obj-$(CONFIG_QTI_BATTERY_CHARGER_VENUS)\t+= qti_battery_charger_venus.o\n"
    "obj-$(CONFIG_STAR_VOLT_SOC)\t\t+= star_volt_soc.o\n",
    "build star_volt_soc.o")

# ---------------------------------------------------------------------------
# 3. Battery charger drivers (generic = star_dsl_defconfig, venus = alternative)
# ---------------------------------------------------------------------------
DT_OLD = ('\tof_property_read_u32(node, "qcom,shutdown-voltage",\n'
          '\t\t\t\t&bcdev->shutdown_volt_mv);\n')
DT_NEW = ('\t/*\n'
          '\t * star low-voltage: qcom,shutdown-voltage lives in the vendor dtb,\n'
          '\t * which is part of the STOCK boot image and is not rebuilt here.\n'
          '\t * Override the 3400 mV stock value with the tunable threshold.\n'
          '\t */\n'
          '\t{\n'
          '\t\tu32 dt_shutdown_mv = 0;\n'
          '\n'
          '\t\tof_property_read_u32(node, "qcom,shutdown-voltage",\n'
          '\t\t\t\t&dt_shutdown_mv);\n'
          '\t\tbcdev->shutdown_volt_mv = star_volt_soc_shutdown_mv();\n'
          '\t\tpr_info("shutdown voltage: DT=%u mV -> %d mV\\n",\n'
          '\t\t\tdt_shutdown_mv, bcdev->shutdown_volt_mv);\n'
          '\t}\n')

CHECK_OLD = ('\tif (pst->prop[BATT_VOLT_NOW] / 1000 > bcdev->shutdown_volt_mv) {\n'
             '\t\tpr_debug("Battery voltage is > %d mV\\n",\n'
             '\t\t\tbcdev->shutdown_volt_mv);\n'
             '\t\treturn;\n'
             '\t}\n')
CHECK_NEW = ('\t/* star low-voltage: filter + debounce the voltage before power-off,\n'
             '\t * so a momentary load sag cannot kill the phone above the real\n'
             '\t * cutoff.  All knobs live in /sys/module/star_volt_soc/parameters. */\n'
             '\tif (!star_volt_soc_should_shutdown(pst->prop[BATT_VOLT_NOW] / 1000)) {\n'
             '\t\treturn;\n'
             '\t}\n')

# --- generic driver (the one star_dsl_defconfig builds) ---
GEN = SUPPLY / "qti_battery_charger.c"
sub(GEN, "#include <linux/hwid.h>\n",
    '#include <linux/hwid.h>\n#include "star_volt_soc.h"\n', "include remap header")
sub(GEN,
    '\t\tif(bcdev->fake_soc >= 0 && bcdev->fake_soc <= 100)\n'
    '\t\t\tpval->intval = bcdev->fake_soc;\n\n'
    '\t\tbreak;\n',
    '\t\tif(bcdev->fake_soc >= 0 && bcdev->fake_soc <= 100)\n'
    '\t\t\tpval->intval = bcdev->fake_soc;\n\n'
    '\t\t/* star low-voltage: report the rebuilt voltage -> SOC table. */\n'
    '\t\t(void)read_property_id(bcdev, pst, BATT_VOLT_NOW);\n'
    '\t\tpval->intval = star_volt_soc_apply(pval->intval,\n'
    '\t\t\t(int)READ_ONCE(pst->prop[BATT_VOLT_NOW]),\n'
    '\t\t\t(int)READ_ONCE(pst->prop[BATT_STATUS]));\n'
    '\t\tbreak;\n',
    "hook POWER_SUPPLY_PROP_CAPACITY")
sub(GEN, DT_OLD, DT_NEW, "override qcom,shutdown-voltage from vendor dtb")
sub(GEN, CHECK_OLD, CHECK_NEW, "use tunable shutdown voltage")

# Android's BatteryService also force-shuts the phone down when the battery
# power_supply reports a critical health (DEAD/UNKNOWN/...) - that is what
# produces the "30 second shutdown countdown" popup.  Report GOOD health
# whenever the (filtered) voltage is above the hard cutoff so userspace never
# independently powers off; the kernel path (star_volt_soc_should_shutdown)
# remains the sole authority at the real cutoff.
GEN_HEALTH_OLD = '\tcase POWER_SUPPLY_PROP_TEMP:\n'
GEN_HEALTH_NEW = (
    '\tcase POWER_SUPPLY_PROP_HEALTH:\n'
    '\t\tpval->intval = pst->prop[prop_id];\n'
    '\t\tif (IS_ENABLED(CONFIG_STAR_VOLT_SOC)) {\n'
    '\t\t\t(void)read_property_id(bcdev, pst, BATT_VOLT_NOW);\n'
    '\t\t\tif ((int)READ_ONCE(pst->prop[BATT_VOLT_NOW]) >\n'
    '\t\t\t    star_volt_soc_hardcutoff_mv() * 1000)\n'
    '\t\t\t\tpval->intval = POWER_SUPPLY_HEALTH_GOOD;\n'
    '\t\t}\n'
    '\t\tbreak;\n\n'
    '\tcase POWER_SUPPLY_PROP_TEMP:\n'
)
sub(GEN, GEN_HEALTH_OLD, GEN_HEALTH_NEW, "force GOOD health above hard cutoff")

# Some MIUI/HyperOS builds key the "battery low, N seconds" countdown off the
# reported voltage.  Clamp the voltage shown to userspace up to a safe floor
# while discharging; the kernel shutdown path still uses the real voltage.
GEN_VOLT_OLD = ('\tcase POWER_SUPPLY_PROP_TEMP:\n')
GEN_VOLT_NEW = (
    '\tcase POWER_SUPPLY_PROP_VOLTAGE_NOW:\n'
    '\tcase POWER_SUPPLY_PROP_VOLTAGE_OCV:\n'
    '\t\tpval->intval = pst->prop[prop_id];\n'
    '\t\tif (IS_ENABLED(CONFIG_STAR_VOLT_SOC)) {\n'
    '\t\t\tint vsoc_st = (int)READ_ONCE(pst->prop[BATT_STATUS]);\n'
    '\t\t\tif (vsoc_st == POWER_SUPPLY_STATUS_UNKNOWN)\n'
    '\t\t\t\t(void)read_property_id(bcdev, pst, BATT_STATUS);\n'
    '\t\t\tpval->intval = star_volt_soc_report_volt_uv(\n'
    '\t\t\t\tpval->intval,\n'
    '\t\t\t\t(int)READ_ONCE(pst->prop[BATT_STATUS]));\n'
    '\t\t}\n'
    '\t\tbreak;\n\n'
    '\tcase POWER_SUPPLY_PROP_TEMP:\n'
)
sub(GEN, GEN_VOLT_OLD, GEN_VOLT_NEW, "clamp reported voltage to floor")

# The gauge's coulomb counter is the last value that can disagree with the
# percentage we report.  On a drifted pack it can read ~5% while the voltage
# table says 70%; MIUI/HyperOS security center does its own mAh maths from
# charge_counter, concludes "nearly empty" and keeps popping the low-battery
# countdown no matter what capacity says.  Report charge_full * mapped / 100
# instead so every field on the battery node agrees.
CC_OLD = ('\tdefault:\n'
          '\t\tpval->intval = pst->prop[prop_id];\n'
          '\t\tbreak;\n'
          '\t}\n')
CC_NEW = ('\tcase POWER_SUPPLY_PROP_CHARGE_COUNTER:\n'
          '\t\tpval->intval = pst->prop[prop_id];\n'
          '\t\tif (IS_ENABLED(CONFIG_STAR_VOLT_SOC)) {\n'
          '\t\t\tint cc_full = 0;\n'
          '\n'
          '\t\t\tif (read_property_id(bcdev, pst, BATT_CHG_FULL) >= 0)\n'
          '\t\t\t\tcc_full = (int)READ_ONCE(pst->prop[BATT_CHG_FULL]);\n'
          '\t\t\tpval->intval = star_volt_soc_scale_cc(pval->intval,\n'
          '\t\t\t\t\t\t\t      cc_full);\n'
          '\t\t}\n'
          '\t\tbreak;\n'
          '\tdefault:\n'
          '\t\tpval->intval = pst->prop[prop_id];\n'
          '\t\tbreak;\n'
          '\t}\n')
sub(GEN, CC_OLD, CC_NEW, "scale charge_counter to mapped SOC")

# --- venus driver (kept in sync for CONFIG_QTI_BATTERY_CHARGER_VENUS builds) ---
VEN = SUPPLY / "qti_battery_charger_venus.c"
sub(VEN, "#include <linux/workqueue.h>\n",
    '#include <linux/workqueue.h>\n#include "star_volt_soc.h"\n', "include remap header")
sub(VEN,
    '\t\tpval->intval = battery_chg_get_ui_capacity(bcdev, pst,\n'
    '\t\t\t\tpval->intval, remaining_uah, rm_valid,\n'
    '\t\t\t\texpanded, &changed);\n'
    '\t\tbreak;\n',
    '\t\tpval->intval = battery_chg_get_ui_capacity(bcdev, pst,\n'
    '\t\t\t\tpval->intval, remaining_uah, rm_valid,\n'
    '\t\t\t\texpanded, &changed);\n'
    '\t\t/* star low-voltage: rebuild the voltage -> SOC curve last. */\n'
    '\t\t(void)read_property_id(bcdev, pst, BATT_VOLT_NOW);\n'
    '\t\tpval->intval = star_volt_soc_apply(pval->intval,\n'
    '\t\t\t(int)READ_ONCE(pst->prop[BATT_VOLT_NOW]),\n'
    '\t\t\t(int)READ_ONCE(pst->prop[BATT_STATUS]));\n'
    '\t\tbreak;\n',
    "hook POWER_SUPPLY_PROP_CAPACITY")
sub(VEN, DT_OLD, DT_NEW, "override qcom,shutdown-voltage from vendor dtb")
sub(VEN, CHECK_OLD, CHECK_NEW, "use tunable shutdown voltage")
sub(VEN, GEN_HEALTH_OLD, GEN_HEALTH_NEW, "force GOOD health above hard cutoff")
sub(VEN, GEN_VOLT_OLD, GEN_VOLT_NEW, "clamp reported voltage to floor")

# venus serves CHARGE_COUNTER from its own early-return branch (it reads the
# remaining-uAh straight from the fuel gauge), so it needs its own hook.
VEN_CC_OLD = ('\tif (prop == POWER_SUPPLY_PROP_CHARGE_COUNTER &&\n'
              '\t    READ_ONCE(bcdev->battery_expanded) &&\n'
              '\t    !battery_chg_read_fg_remaining_uah(bcdev, &remaining_uah)) {\n'
              '\t\tpval->intval = remaining_uah;\n'
              '\t\treturn 0;\n'
              '\t}\n')
VEN_CC_NEW = ('\tif (prop == POWER_SUPPLY_PROP_CHARGE_COUNTER &&\n'
              '\t    READ_ONCE(bcdev->battery_expanded) &&\n'
              '\t    !battery_chg_read_fg_remaining_uah(bcdev, &remaining_uah)) {\n'
              '\t\tpval->intval = remaining_uah;\n'
              '\t\tif (IS_ENABLED(CONFIG_STAR_VOLT_SOC)) {\n'
              '\t\t\tbattery_chg_refresh_pack_capacity_uah(bcdev, pst,\n'
              '\t\t\t\t\t\t\t     &learned_full_uah);\n'
              '\t\t\tpval->intval = star_volt_soc_scale_cc(pval->intval,\n'
              '\t\t\t\t\t\t\t      (int)learned_full_uah);\n'
              '\t\t}\n'
              '\t\treturn 0;\n'
              '\t}\n')
sub(VEN, VEN_CC_OLD, VEN_CC_NEW, "scale charge_counter (venus early path)")
sub(VEN, CC_OLD, CC_NEW, "scale charge_counter to mapped SOC")

# ---------------------------------------------------------------------------
# 4. QG fuel gauge defaults (for defconfigs that enable QCOM_POWER_SUPPLY /
#    QPNP_QG; star_dsl_defconfig does not build this directory).
# ---------------------------------------------------------------------------
QG = SUPPLY / "qcom" / "qpnp-qg.c"
for name, old, new in (
    ("DEFAULT_VBATT_EMPTY_MV", 3200, SHUTDOWN_MV),
    ("DEFAULT_VBATT_EMPTY_COLD_MV", 3000, SHUTDOWN_MV),
    ("DEFAULT_VBATT_CUTOFF_MV", 3400, SHUTDOWN_MV),
    ("DEFAULT_VBATT_LOW_MV", 3500, SHUTDOWN_MV + 220),
    ("DEFAULT_VBATT_LOW_COLD_MV", 3800, SHUTDOWN_MV + 320),
):
    pattern = rf'^#define {name}\t+{old}$'
    resub(QG, pattern,
          lambda m, n=name, v=new: f"#define {n}\t\t{v}",
          f"{name} -> {new}")

# ---------------------------------------------------------------------------
# 5. Self-contained build script.  Using our own script (instead of patching
#    upstream build_star.sh) keeps the build reproducible if upstream edits
#    that file; it enables CONFIG_STAR_VOLT_SOC and only builds Image.gz.
# ---------------------------------------------------------------------------
build_script = (REPO / "overlay" / "build_lowvolt.sh").read_text(encoding="utf-8")
if build_script.count("@LOWVOLT_TAG@") != 1:
    sys.exit("overlay/build_lowvolt.sh: @LOWVOLT_TAG@ placeholder missing")
write(Path("build_lowvolt.sh"), build_script.replace("@LOWVOLT_TAG@", LOCALVERSION))
(KERNEL / "build_lowvolt.sh").chmod(0o755)
changes.append(f"build_lowvolt.sh: added (tag {LOCALVERSION})")

# ---------------------------------------------------------------------------
info = (
    "star / Xiaomi Mi 11 Ultra low-voltage kernel\n"
    "upstream      : ikun-1145141/android_kernel_xiaomi_sm8350_star\n"
    f"shutdown_mv   : {SHUTDOWN_MV} mV (stock 3400 mV)\n"
    f"volt_soc_table: {TABLE}\n"
    f"localversion  : {LOCALVERSION}\n"
    "runtime knobs : /sys/module/star_volt_soc/parameters/\n"
)
write(Path("LOWVOLT_BUILD_INFO.txt"), info)

print("Applied low-voltage patches:")
for c in changes:
    print("  - " + c)
print()
print(info)
